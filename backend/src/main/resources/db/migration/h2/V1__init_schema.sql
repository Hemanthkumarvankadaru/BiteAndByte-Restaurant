-- BiteAndByte Restaurant initial schema (H2, used by the dev profile in PostgreSQL mode).
-- Keep in step with db/migration/h2 and db/migration/oracle.
-- Timestamps are TIMESTAMP(6) holding UTC. Money is NUMERIC(10,2) in INR.

CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        VARCHAR(50)  NOT NULL,
    email           VARCHAR(120) NOT NULL,
    phone           VARCHAR(15)  NOT NULL,
    password_hash   VARCHAR(100) NOT NULL,
    full_name       VARCHAR(100) NOT NULL,
    age             INTEGER,
    gender          VARCHAR(20),
    role            VARCHAR(20)  NOT NULL,
    is_active       BOOLEAN      DEFAULT TRUE NOT NULL,
    created_at      TIMESTAMP(6) NOT NULL,
    updated_at      TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT uk_users_email    UNIQUE (email),
    CONSTRAINT uk_users_phone    UNIQUE (phone),
    CONSTRAINT ck_users_role     CHECK (role IN ('CUSTOMER', 'ADMIN')),
    CONSTRAINT ck_users_age      CHECK (age IS NULL OR (age BETWEEN 13 AND 120))
);

CREATE TABLE refresh_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL,
    token_hash  VARCHAR(64)  NOT NULL,
    created_at  TIMESTAMP(6) NOT NULL,
    expires_at  TIMESTAMP(6) NOT NULL,
    revoked_at  TIMESTAMP(6),
    CONSTRAINT uk_refresh_tokens_hash UNIQUE (token_hash),
    CONSTRAINT fk_refresh_tokens_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);
CREATE INDEX ix_refresh_tokens_user ON refresh_tokens (user_id);

CREATE TABLE addresses (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL,
    label       VARCHAR(30),
    street      VARCHAR(200) NOT NULL,
    city        VARCHAR(60)  NOT NULL,
    state       VARCHAR(60)  NOT NULL,
    pincode     VARCHAR(6)   NOT NULL,
    landmark    VARCHAR(100),
    is_default  BOOLEAN      DEFAULT FALSE NOT NULL,
    created_at  TIMESTAMP(6) NOT NULL,
    updated_at  TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_addresses_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);
CREATE INDEX ix_addresses_user ON addresses (user_id);

CREATE TABLE categories (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(60)  NOT NULL,
    description    VARCHAR(500),
    image_url      VARCHAR(500),
    display_order  INTEGER      DEFAULT 0 NOT NULL,
    is_active      BOOLEAN      DEFAULT TRUE NOT NULL,
    created_at     TIMESTAMP(6) NOT NULL,
    updated_at     TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_categories_name UNIQUE (name)
);

CREATE TABLE menu_items (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id     BIGINT        NOT NULL,
    name            VARCHAR(100)  NOT NULL,
    description     VARCHAR(1000),
    price           NUMERIC(10,2) NOT NULL,
    image_url       VARCHAR(500),
    stock_quantity  INTEGER       DEFAULT 0 NOT NULL,
    is_available    BOOLEAN       DEFAULT TRUE NOT NULL,
    is_veg          BOOLEAN       DEFAULT FALSE NOT NULL,
    is_deleted      BOOLEAN       DEFAULT FALSE NOT NULL,
    version         BIGINT        DEFAULT 0 NOT NULL,
    created_at      TIMESTAMP(6)  NOT NULL,
    updated_at      TIMESTAMP(6)  NOT NULL,
    CONSTRAINT fk_menu_items_category FOREIGN KEY (category_id) REFERENCES categories (id),
    CONSTRAINT ck_menu_items_price    CHECK (price > 0),
    CONSTRAINT ck_menu_items_stock    CHECK (stock_quantity >= 0)
);
CREATE INDEX ix_menu_items_category ON menu_items (category_id);

CREATE TABLE cart_items (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT       NOT NULL,
    menu_item_id  BIGINT       NOT NULL,
    quantity      INTEGER      NOT NULL,
    added_at      TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_cart_items_user_item UNIQUE (user_id, menu_item_id),
    CONSTRAINT fk_cart_items_user      FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_cart_items_menu_item FOREIGN KEY (menu_item_id) REFERENCES menu_items (id),
    CONSTRAINT ck_cart_items_quantity  CHECK (quantity > 0)
);
CREATE INDEX ix_cart_items_menu_item ON cart_items (menu_item_id);

CREATE TABLE orders (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            BIGINT        NOT NULL,
    address_id         BIGINT,
    order_number       VARCHAR(30)   NOT NULL,
    status             VARCHAR(30)   NOT NULL,
    payment_method     VARCHAR(20)   NOT NULL,
    subtotal           NUMERIC(10,2) NOT NULL,
    tax_amount         NUMERIC(10,2) NOT NULL,
    delivery_charge    NUMERIC(10,2) NOT NULL,
    grand_total        NUMERIC(10,2) NOT NULL,
    delivery_name      VARCHAR(100)  NOT NULL,
    delivery_phone     VARCHAR(15)   NOT NULL,
    delivery_street    VARCHAR(200)  NOT NULL,
    delivery_city      VARCHAR(60)   NOT NULL,
    delivery_state     VARCHAR(60)   NOT NULL,
    delivery_pincode   VARCHAR(6)    NOT NULL,
    delivery_landmark  VARCHAR(100),
    cancel_reason      VARCHAR(255),
    ordered_at         TIMESTAMP(6)  NOT NULL,
    delivered_at       TIMESTAMP(6),
    cancelled_at       TIMESTAMP(6),
    created_at         TIMESTAMP(6)  NOT NULL,
    updated_at         TIMESTAMP(6)  NOT NULL,
    CONSTRAINT uk_orders_order_number UNIQUE (order_number),
    CONSTRAINT fk_orders_user    FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_orders_address FOREIGN KEY (address_id) REFERENCES addresses (id) ON DELETE SET NULL,
    CONSTRAINT ck_orders_status  CHECK (status IN ('PENDING', 'CONFIRMED', 'PREPARING', 'OUT_FOR_DELIVERY', 'DELIVERED', 'CANCELLED')),
    CONSTRAINT ck_orders_payment_method CHECK (payment_method IN ('COD', 'RAZORPAY'))
);
CREATE INDEX ix_orders_user_ordered ON orders (user_id, ordered_at);
CREATE INDEX ix_orders_status_ordered ON orders (status, ordered_at);
CREATE INDEX ix_orders_address ON orders (address_id);

CREATE TABLE order_items (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      BIGINT        NOT NULL,
    menu_item_id  BIGINT        NOT NULL,
    item_name     VARCHAR(100)  NOT NULL,
    quantity      INTEGER       NOT NULL,
    unit_price    NUMERIC(10,2) NOT NULL,
    line_total    NUMERIC(10,2) NOT NULL,
    CONSTRAINT fk_order_items_order     FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT fk_order_items_menu_item FOREIGN KEY (menu_item_id) REFERENCES menu_items (id),
    CONSTRAINT ck_order_items_quantity  CHECK (quantity > 0)
);
CREATE INDEX ix_order_items_order ON order_items (order_id);
CREATE INDEX ix_order_items_menu_item ON order_items (menu_item_id);

CREATE TABLE payments (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id             BIGINT        NOT NULL,
    method               VARCHAR(20)   NOT NULL,
    status               VARCHAR(20)   NOT NULL,
    amount               NUMERIC(10,2) NOT NULL,
    razorpay_order_id    VARCHAR(64),
    razorpay_payment_id  VARCHAR(64),
    razorpay_signature   VARCHAR(128),
    paid_at              TIMESTAMP(6),
    created_at           TIMESTAMP(6)  NOT NULL,
    updated_at           TIMESTAMP(6)  NOT NULL,
    CONSTRAINT fk_payments_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT uk_payments_rzp_payment UNIQUE (razorpay_payment_id),
    CONSTRAINT ck_payments_method CHECK (method IN ('COD', 'RAZORPAY')),
    CONSTRAINT ck_payments_status CHECK (status IN ('PENDING', 'SUCCESS', 'FAILED', 'REFUNDED'))
);
CREATE INDEX ix_payments_order ON payments (order_id);
CREATE INDEX ix_payments_rzp_order ON payments (razorpay_order_id);
